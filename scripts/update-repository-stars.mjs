import { readFile, writeFile } from 'node:fs/promises'
import process from 'node:process'

const repositorySourceUrl = new URL('../src/repositories/repositories.js', import.meta.url)
const starCacheUrl = new URL('../src/repositories/repository-stars.js', import.meta.url)
const githubRepositoryPattern = /slug:\s*'([^']+)'[\s\S]*?github:\s*'https:\/\/github\.com\/([^/'\s]+)\/([^/'\s]+)'/g

const source = await readFile(repositorySourceUrl, 'utf8')
const repositories = [...source.matchAll(githubRepositoryPattern)].map((match) => ({
  slug: match[1],
  owner: match[2],
  name: match[3],
}))

if (repositories.length === 0) throw new Error('No GitHub repositories found in repositories.js')

const headers = {
  Accept: 'application/vnd.github+json',
  'User-Agent': 'openrepo-star-updater',
  'X-GitHub-Api-Version': '2026-03-10',
}
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`

const stars = {}
for (const repository of repositories) {
  const response = await fetch(`https://api.github.com/repos/${repository.owner}/${repository.name}`, { headers })
  if (!response.ok) {
    throw new Error(`GitHub returned ${response.status} for ${repository.owner}/${repository.name}`)
  }

  const payload = await response.json()
  if (!Number.isSafeInteger(payload.stargazers_count) || payload.stargazers_count < 0) {
    throw new Error(`Invalid stargazers_count for ${repository.owner}/${repository.name}`)
  }
  stars[repository.slug] = payload.stargazers_count
}

const output = [
  '// Generated by scripts/update-repository-stars.mjs. Do not edit manually.',
  `export const repositoryStarsUpdatedAt = '${new Date().toISOString()}'`,
  '',
  'export const repositoryStars = {',
  ...repositories.map(({ slug }) => `  '${slug}': ${stars[slug]},`),
  '}',
  '',
].join('\n')

await writeFile(starCacheUrl, output, 'utf8')
console.log(`Updated ${repositories.length} repository star counts.`)
